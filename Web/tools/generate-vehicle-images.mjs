import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const toolDirectory = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(toolDirectory, '..');
const manifestPath = resolve(webRoot, 'public/vehicles/manifest.json');
const outputPath = resolve(webRoot, 'src/app/data/stock-vehicle-images.generated.ts');

const rawManifest = JSON.parse(await readFile(manifestPath, 'utf8'));
const images = {};

for (const [rawCode, rawDetails] of Object.entries(rawManifest)) {
    if (!rawDetails || typeof rawDetails !== 'object') {
        continue;
    }

    const code = rawCode.trim().toLowerCase().replace(/\.odf$/i, '');
    const thumbnailUrl = typeof rawDetails.thumbnailUrl === 'string'
        ? rawDetails.thumbnailUrl.trim()
        : '';

    // Catalog images must be served by this application. External URLs remain attribution-only
    // metadata and are deliberately excluded from the generated browser lookup.
    if (!code || !thumbnailUrl.startsWith('/vehicles/')) {
        if (thumbnailUrl) {
            console.warn(`Skipping externally hosted vehicle image for ${code || rawCode}: ${thumbnailUrl}`);
        }
        continue;
    }

    images[code] = {
        thumbnailUrl,
        sourceUrl: typeof rawDetails.sourceUrl === 'string' ? rawDetails.sourceUrl : null
    };
}

const sortedImages = Object.fromEntries(
    Object.entries(images).sort(([left], [right]) => left.localeCompare(right))
);
const serialized = JSON.stringify(sortedImages, null, 4)
    .replaceAll('"thumbnailUrl"', 'thumbnailUrl')
    .replaceAll('"sourceUrl"', 'sourceUrl');

const output = `// Generated by Web/tools/generate-vehicle-images.mjs. Do not edit by hand.\n\n` +
`export interface StockVehicleImageDefinition {\n` +
`    thumbnailUrl: string;\n` +
`    sourceUrl: string | null;\n` +
`}\n\n` +
`export const GENERATED_STOCK_VEHICLE_IMAGES: Readonly<Record<string, StockVehicleImageDefinition>> =\n` +
`    Object.freeze(${serialized});\n`;

await writeFile(outputPath, output, 'utf8');
console.log(`Generated ${Object.keys(sortedImages).length} self-hosted vehicle image mappings.`);
